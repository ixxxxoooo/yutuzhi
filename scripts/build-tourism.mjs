import { parsePathRings, ptInRings } from '../src/geometry.js';

const mapData = JSON.parse(fs.readFileSync('src/map-data.json', 'utf8'));
const coarsePaths = JSON.parse(fs.readFileSync('src/map-paths-coarse.json', 'utf8'));

const DEG = Math.PI / 180;
const PHI0 = 25 * DEG;
const PHI1 = 47 * DEG;
const LAM0 = 105 * DEG;
const N_CONE = (Math.sin(PHI0) + Math.sin(PHI1)) / 2;
const C_CONE = 1 + Math.sin(PHI0) * Math.sin(PHI1);
const PAD = 16;
const BX0 = -0.41107467;
const BY0 = 1.05083385;
const PROJ_K = 1279.457409;

const round1 = n => Math.round(n * 10) / 10;

const lonLatToSvg = (lon, lat) => {
  const r = Math.sqrt(Math.max(0, C_CONE - 2 * N_CONE * Math.sin(lat * DEG))) / N_CONE;
  const theta = N_CONE * (lon * DEG - LAM0);
  const fx = r * Math.sin(theta);
  const fy = r * Math.cos(theta);
  return [round1(PAD + (fx - BX0) * PROJ_K), round1(PAD + (fy - BY0) * PROJ_K)];
};

const toPy = s => pinyin(s, { toneType: 'none', type: 'array' }).join('').toLowerCase().replace(/[^a-z]/g, '');
const toPi = s => pinyin(s, { pattern: 'first', toneType: 'none', type: 'array' }).join('').toLowerCase().replace(/[^a-z]/g, '');

// 预解析各县级单元的多边形环，用于将景点经纬度自动归属到精确的市、区县
const unitsByProv = new Map();
for (const u of mapData.units) {
  const d = u.d || coarsePaths[u.code] || '';
  const rings = d ? parsePathRings(d) : [];
  if (!unitsByProv.has(u.province)) unitsByProv.set(u.province, []);
  unitsByProv.get(u.province).push({ ...u, rings });
}

const findUnitForPoint = (provCode, x, y) => {
  const list = unitsByProv.get(provCode) || [];
  for (const u of list) {
    if (!u.bbox) continue;
    const [bx, by, bw, bh] = u.bbox;
    if (x < bx || x > bx + bw || y < by || y > by + bh) continue;
    if (u.rings.length && ptInRings(x, y, u.rings)) return u;
  }
  // 若点在海岛或边界容差外，取同省距离最近的区县
  let best = list[0] || null;
  let bestD = Infinity;
  for (const u of list) {
    const cx = u.seat ? u.seat[0] : u.label ? u.label[0] : (u.bbox[0] + u.bbox[2] / 2);
    const cy = u.seat ? u.seat[1] : u.label ? u.label[1] : (u.bbox[1] + u.bbox[3] / 2);
    const d2 = (x - cx) ** 2 + (y - cy) ** 2;
    if (d2 < bestD) {
      bestD = d2;
      best = u;
    }
  }
  return best;
};

